"""Typed access to ``simulation/cell.yaml``.

The YAML file is generated by ``simulation/generate_cell.py`` and is the single
source of truth for the cell. This module reads it and nothing else: it holds
no geometry of its own, deliberately, so that there is exactly one place where
a dimension can be wrong.

It stays free of any dependency on the motion or perception packages, because
every one of them depends on it.
"""

from __future__ import annotations

from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np
import yaml

DEFAULT_CELL_PATH = Path(__file__).resolve().parents[3] / "simulation" / "cell.yaml"


@dataclass(frozen=True)
class PartSpec:
    """A part on the conveyor. Axis-aligned box in its own frame."""

    name: str
    size: np.ndarray
    mass: float
    friction: float

    @property
    def footprint(self) -> np.ndarray:
        """The two horizontal dimensions when the part lies on its largest face."""
        return np.sort(self.size)[1:][::-1]

    def resting_sizes(self) -> List[np.ndarray]:
        """The three stable resting orientations, as (x, y, z) extents.

        A box on a belt rests on one of three distinct face pairs. Which one it
        is changes the graspable width and the height the camera sees, so the
        randomised benchmark samples over it rather than always presenting the
        part flat.
        """
        x, y, z = (float(value) for value in self.size)
        return [np.array([x, y, z]), np.array([x, z, y]), np.array([z, y, x])]

    def resting_weights(self) -> np.ndarray:
        """How likely each resting face is, normalised.

        Weighted by the ratio of the shorter base dimension to the height,
        which is a crude but monotone stand-in for the tipping angle: a
        100 x 8 mm coupon balanced on its long edge, 70 mm tall, is a stable
        equilibrium in the strict sense and is not something a vibratory feeder
        delivers. Weighting the three faces equally, as the first version of
        this did, put a quarter of the benchmark's parts on edge and made the
        headline success rate a statement about a part presentation that does
        not occur.
        """
        weights = []
        for size in self.resting_sizes():
            base = float(min(size[0], size[1]))
            weights.append((base / float(size[2])) ** 2)
        weights = np.asarray(weights, dtype=float)
        return weights / weights.sum()


@dataclass(frozen=True)
class GripperSpec:
    """Parallel-jaw gripper geometry and timing."""

    tcp_offset: float
    max_opening: float
    min_opening: float
    finger_length: float
    finger_width: float
    finger_thickness: float
    palm_size: np.ndarray
    close_time: float
    grip_force: float


@dataclass(frozen=True)
class CameraSpec:
    """Pinhole depth camera, eye-in-hand.

    ``extrinsic`` is the ground-truth flange-to-optical-frame transform. The
    calibration routine is not allowed to read it; it exists so the simulated
    camera can render, and so the calibration residual has something to be a
    residual against.
    """

    width: int
    height: int
    fx: float
    fy: float
    cx: float
    cy: float
    depth_noise_base: float
    depth_noise_quadratic: float
    depth_min: float
    depth_max: float
    extrinsic_xyz: np.ndarray
    extrinsic_rpy: np.ndarray

    @property
    def intrinsic_matrix(self) -> np.ndarray:
        return np.array([[self.fx, 0.0, self.cx], [0.0, self.fy, self.cy], [0.0, 0.0, 1.0]])

    @property
    def extrinsic(self) -> np.ndarray:
        from cell_common.transforms import from_rpy

        return from_rpy(*self.extrinsic_rpy, xyz=self.extrinsic_xyz)

    def noise_sigma(self, depth: np.ndarray) -> np.ndarray:
        """Depth noise standard deviation at a given range, in metres.

        Constant plus quadratic, which is the shape stereo depth cameras
        actually have: error grows with the square of range because disparity
        is inversely proportional to it.
        """
        depth = np.asarray(depth, dtype=float)
        return self.depth_noise_base + self.depth_noise_quadratic * depth**2


@dataclass(frozen=True)
class CellSpec:
    """Everything in ``cell.yaml``, with the raw dictionary still available."""

    raw: Dict
    path: Path

    # -- geometry ----------------------------------------------------------
    @property
    def obstacles(self) -> List[Dict]:
        return self.raw["obstacles"]

    @property
    def arm_base_xyz(self) -> np.ndarray:
        return np.asarray(self.raw["frames"]["arm_base_xyz"], dtype=float)

    @property
    def conveyor_top(self) -> float:
        return float(self.raw["frames"]["conveyor_top"])

    @property
    def fixture_top(self) -> float:
        return float(self.raw["frames"]["fixture_top"])

    @property
    def place_xyz(self) -> np.ndarray:
        return np.asarray(self.raw["frames"]["place_xyz"], dtype=float)

    @property
    def scan_camera_xyz(self) -> np.ndarray:
        return np.asarray(self.raw["frames"]["scan_camera_xyz"], dtype=float)

    @property
    def scan_target_xyz(self) -> np.ndarray:
        return np.asarray(self.raw["frames"]["scan_target_xyz"], dtype=float)

    @property
    def part_region(self) -> Dict[str, Tuple[float, float]]:
        return {key: (float(low), float(high)) for key, (low, high) in self.raw["part_region"].items()}

    @property
    def region_margin(self) -> float:
        return float(self.raw["region_margin"])

    def perception_workspace(self) -> Tuple[Tuple[float, float], Tuple[float, float]]:
        """The region-of-interest crop, as ((x_low, x_high), (y_low, y_high))."""
        region = self.part_region
        margin = self.region_margin
        return (
            (region["x"][0] - margin, region["x"][1] + margin),
            (region["y"][0] - margin, region["y"][1] + margin),
        )

    @property
    def home_joints(self) -> np.ndarray:
        return np.asarray(self.raw["home_joints"], dtype=float)

    @property
    def joint_names(self) -> List[str]:
        return list(self.raw["joint_names"])

    @property
    def inspection_points(self) -> np.ndarray:
        return np.asarray(self.raw["inspection_points"], dtype=float)

    # -- catalogue ---------------------------------------------------------
    @property
    def parts(self) -> List[PartSpec]:
        return [
            PartSpec(
                name=entry["name"],
                size=np.asarray(entry["size"], dtype=float),
                mass=float(entry["mass"]),
                friction=float(entry["friction"]),
            )
            for entry in self.raw["parts"]
        ]

    def part(self, name: str) -> PartSpec:
        for candidate in self.parts:
            if candidate.name == name:
                return candidate
        raise KeyError(f"no part named {name!r} in {self.path}")

    @property
    def gripper(self) -> GripperSpec:
        entry = dict(self.raw["gripper"])
        entry["palm_size"] = np.asarray(entry["palm_size"], dtype=float)
        return GripperSpec(**entry)

    @property
    def camera(self) -> CameraSpec:
        entry = dict(self.raw["camera"])
        entry["extrinsic_xyz"] = np.asarray(entry["extrinsic_xyz"], dtype=float)
        entry["extrinsic_rpy"] = np.asarray(entry["extrinsic_rpy"], dtype=float)
        return CameraSpec(**entry)


@lru_cache(maxsize=4)
def load_cell(path: Optional[str] = None) -> CellSpec:
    """Load and cache the cell description.

    Cached because the benchmark loads it once per trial and parsing YAML two
    hundred times to get the same answer is a waste of a second and a half.
    """
    resolved = Path(path) if path is not None else DEFAULT_CELL_PATH
    if not resolved.exists():
        raise FileNotFoundError(f"{resolved} is missing. Run `make cell` to generate it.")
    return CellSpec(raw=yaml.safe_load(resolved.read_text(encoding="utf-8")), path=resolved)


def sample_part_pose(
    cell: CellSpec,
    rng: np.random.Generator,
    part: Optional[PartSpec] = None,
) -> Dict:
    """Draw one randomised part presentation on the conveyor.

    Position is uniform over the pick region, yaw uniform over the full circle,
    and the resting face is drawn from the three stable ones weighted by
    :meth:`PartSpec.resting_weights`.
    """
    part = part if part is not None else cell.parts[int(rng.integers(len(cell.parts)))]
    region = cell.part_region
    resting = part.resting_sizes()
    face_index = int(rng.choice(len(resting), p=part.resting_weights()))
    size = resting[face_index]
    return {
        "part": part.name,
        "size": size,
        "resting_face": face_index,
        "xyz": np.array(
            [
                float(rng.uniform(*region["x"])),
                float(rng.uniform(*region["y"])),
                cell.conveyor_top + float(size[2]) / 2.0,
            ]
        ),
        "yaw": float(rng.uniform(*region["yaw"])),
        "mass": part.mass,
        "friction": part.friction,
    }


def part_box(pose: Dict, name: str = "part"):
    """A :class:`cell_motion.core.collision.Box` for a sampled part pose.

    Imported lazily so that this module keeps no import-time dependency on the
    motion package.
    """
    from cell_common.transforms import from_rpy
    from cell_motion.core.collision import Box

    return Box(
        name=name,
        size=np.asarray(pose["size"], dtype=float),
        pose=from_rpy(0.0, 0.0, pose["yaw"], xyz=pose["xyz"]),
        kind="part",
    )


def region_corners(cell: CellSpec) -> np.ndarray:
    """The four corners of the pick region at belt height, for reach checks."""
    region = cell.part_region
    return np.array(
        [
            [region["x"][0], region["y"][0], cell.conveyor_top],
            [region["x"][0], region["y"][1], cell.conveyor_top],
            [region["x"][1], region["y"][0], cell.conveyor_top],
            [region["x"][1], region["y"][1], cell.conveyor_top],
        ]
    )


def as_world_sequence(values: Sequence[float]) -> np.ndarray:
    return np.asarray(values, dtype=float)
