"""The cell in Gazebo Harmonic: the generated world, and the arm spawned into it.

    ros2 launch cell_bringup gazebo.launch.py            # headless server
    ros2 launch cell_bringup gazebo.launch.py gui:=true  # with the Gazebo GUI

Modern Gazebo (gz-sim 8, Harmonic) through ``ros_gz_sim``, not Gazebo
Classic, which reached end of life in January 2025. Harmonic rather than
Fortress, the version Humble was released alongside, because Fortress reached
end of life in September 2026; OSRF publishes Humble builds of ``ros_gz`` for
Harmonic as ``ros-humble-ros-gzharmonic``.

What this is and is not: the world is the cell furniture and the light
curtain, generated by ``simulation/generate_cell.py`` from the same table as
everything else, and the arm is spawned from the same xacro the controllers
and MoveIt use. The arm is not driven in Gazebo: motion comes from
``ros2_control`` on mock hardware, and no gz_ros2_control bridge is wired, so
in Gazebo the arm's joints are unactuated. ``docs/limitations.md`` says so.
``test/test_gazebo_world.launch.py`` checks, headless in CI, that the world
loads and the arm spawns into it.
"""

from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, IncludeLaunchDescription
from launch.conditions import IfCondition, UnlessCondition
from launch.launch_description_sources import PythonLaunchDescriptionSource
from launch.substitutions import Command, FindExecutable, LaunchConfiguration, PathJoinSubstitution
from launch_ros.actions import Node
from launch_ros.substitutions import FindPackageShare


def generate_launch_description():
    gui = LaunchConfiguration("gui")
    world = PathJoinSubstitution([FindPackageShare("cell_description"), "worlds", "cell.world"])
    gz_sim = PathJoinSubstitution([FindPackageShare("ros_gz_sim"), "launch", "gz_sim.launch.py"])

    # The arm alone: the world already has the fixtures as static models, and
    # Gazebo has no use for the mock ros2_control block.
    arm = Command(
        [
            PathJoinSubstitution([FindExecutable(name="xacro")]),
            " ",
            PathJoinSubstitution([FindPackageShare("cell_description"), "urdf", "arm_cell.urdf.xacro"]),
            " with_fixtures:=false use_ros2_control:=false",
        ]
    )

    return LaunchDescription(
        [
            DeclareLaunchArgument("gui", default_value="false"),
            # -r runs the simulation on start; -s is the server alone, which is
            # what a container without a display can run.
            IncludeLaunchDescription(
                PythonLaunchDescriptionSource([gz_sim]),
                launch_arguments={"gz_args": ["-r -s -v 2 ", world], "on_exit_shutdown": "true"}.items(),
                condition=UnlessCondition(gui),
            ),
            IncludeLaunchDescription(
                PythonLaunchDescriptionSource([gz_sim]),
                launch_arguments={"gz_args": ["-r -v 2 ", world], "on_exit_shutdown": "true"}.items(),
                condition=IfCondition(gui),
            ),
            Node(
                package="ros_gz_sim",
                executable="create",
                name="spawn_arm",
                output="screen",
                arguments=["-world", "arm_cell", "-name", "arm_cell", "-string", arm],
            ),
        ]
    )
