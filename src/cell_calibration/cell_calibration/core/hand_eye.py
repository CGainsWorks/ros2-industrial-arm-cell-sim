"""Eye-in-hand calibration: recovering the flange-to-camera transform.

The camera is bolted to the wrist. Everything the vision system says is in the
camera's frame, and the robot only takes commands in its own, so the transform
between them -- ``X``, flange to camera optical frame -- is the single number
that decides whether a grasp computed from an image lands on the part. A
millimetre of error in ``X`` is a millimetre of error at every grasp, forever,
and it does not average out.

THE PIPELINE, WHICH IS THE REAL ONE

1. Move the arm to a set of poses that all see a calibration board clamped in
   the cell. The poses are generated by :func:`generate_poses`, which spreads
   them over position *and* orientation on purpose -- see below.
2. At each pose, project the board's corners through the pinhole model, add
   pixel noise, and recover the board's pose in the camera frame by solving
   PnP. This is a real detection-and-PnP front end, not a "measured pose plus
   Gaussian noise" shortcut, because the error PnP actually makes is
   anisotropic -- depth is far less certain than lateral position at these
   angles -- and that anisotropy is what determines how many poses the
   hand-eye solve needs.
3. Form the motion pairs and solve ``A X = X B`` by the Tsai-Lenz method.
4. Report the residual.

WHY THE POSES HAVE TO ROTATE

``A X = X B`` determines the rotation of ``X`` only from motions whose rotation
axes are not parallel, and the translation only from motions that rotate at
all. A set of poses that translates the camera over the board without turning
it -- which is the natural thing to program, and which produces beautiful
board detections every time -- leaves the translation of ``X`` completely
unobservable. The solver returns an answer anyway.
:func:`generate_poses` therefore tilts every pose, and
``analysis/calibration_residual.py`` reports the rotation-axis spread alongside
the residual so that a degenerate pose set is visible rather than merely
wrong.

TWO RESIDUALS, AND ONLY ONE OF THEM EXISTS IN A REAL CELL

* The **ground-truth residual** compares the recovered ``X`` against the one
  the simulator used. It is the honest measure of accuracy and it is available
  only here.
* The **consistency residual** is ``||A X - X B||`` over the motion pairs, plus
  the spread of the reconstructed board pose in the world frame. It needs no
  ground truth, it is what you can compute on a real robot, and it is what
  ``analysis/calibration_residual.py`` reports as the field-usable figure.

Both are reported. They do not agree, and the difference between them is worth
knowing before trusting a calibration on hardware.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np
from scipy.optimize import least_squares
from scipy.spatial.transform import Rotation

from cell_common.cell_model import CameraSpec
from cell_common.transforms import invert, look_at, transform

# Calibration board: a 9 x 7 grid of 20 mm squares, which is an ordinary
# printed target and small enough to sit on the conveyor inside the pick region.
BOARD_COLUMNS = 9
BOARD_ROWS = 7
BOARD_SQUARE = 0.020

# Corner-detection noise, in pixels. A checkerboard corner refined to subpixel
# accuracy on a well-lit target is good to about this.
CORNER_NOISE_PIXELS = 0.15


@dataclass
class CalibrationSample:
    """One pose: where the flange was, and what the camera saw."""

    flange_pose: np.ndarray  # Base to flange, from the robot's joint encoders.
    board_in_camera: np.ndarray  # Camera to board, from PnP.
    reprojection_rms: float
    visible_corners: int


@dataclass
class CalibrationResult:
    """The recovered transform and everything needed to judge it."""

    transform: np.ndarray  # Flange to camera optical frame.
    sample_count: int
    pair_count: int
    consistency_rotation_deg: float
    consistency_translation_mm: float
    board_spread_mm: float
    reprojection_rms: float
    rotation_axis_spread_deg: float

    def error_against(self, truth: np.ndarray) -> Dict[str, float]:
        """Ground-truth error, available only in simulation."""
        delta = invert(np.asarray(truth)) @ self.transform
        rotation = float(np.degrees(np.linalg.norm(Rotation.from_matrix(delta[:3, :3]).as_rotvec())))
        translation = float(np.linalg.norm(delta[:3, 3]) * 1000.0)
        return {"rotation_deg": round(rotation, 4), "translation_mm": round(translation, 4)}

    def as_dict(self) -> Dict:
        return {
            "samples": self.sample_count,
            "pairs": self.pair_count,
            "consistency_rotation_deg": round(self.consistency_rotation_deg, 4),
            "consistency_translation_mm": round(self.consistency_translation_mm, 4),
            "board_spread_mm": round(self.board_spread_mm, 4),
            "reprojection_rms_px": round(self.reprojection_rms, 4),
            "rotation_axis_spread_deg": round(self.rotation_axis_spread_deg, 3),
            "translation_xyz_mm": [round(float(value) * 1000.0, 3) for value in self.transform[:3, 3]],
        }


def board_corners() -> np.ndarray:
    """Corner positions in the board's own frame, z = 0."""
    columns, rows = np.meshgrid(np.arange(BOARD_COLUMNS), np.arange(BOARD_ROWS))
    points = np.stack(
        [
            (columns.ravel() - (BOARD_COLUMNS - 1) / 2.0) * BOARD_SQUARE,
            (rows.ravel() - (BOARD_ROWS - 1) / 2.0) * BOARD_SQUARE,
            np.zeros(columns.size),
        ],
        axis=1,
    )
    return points


def _skew(vector: np.ndarray) -> np.ndarray:
    """The 3x3 matrix that acts as a cross product with ``vector``."""
    x, y, z = vector
    return np.array([[0.0, -z, y], [z, 0.0, -x], [-y, x, 0.0]])


def project_corners(board_pose_in_camera: np.ndarray, camera: CameraSpec) -> np.ndarray:
    """Project the board's corners into the image. NaN where behind or outside."""
    points = board_corners() @ board_pose_in_camera[:3, :3].T + board_pose_in_camera[:3, 3]
    with np.errstate(divide="ignore", invalid="ignore"):
        u = camera.fx * points[:, 0] / points[:, 2] + camera.cx
        v = camera.fy * points[:, 1] / points[:, 2] + camera.cy
    pixels = np.column_stack([u, v])
    outside = (
        (points[:, 2] <= 1e-6)
        | (u < 0)
        | (u > camera.width - 1)
        | (v < 0)
        | (v > camera.height - 1)
    )
    pixels[outside] = np.nan
    return pixels


def solve_pnp(pixels: np.ndarray, camera: CameraSpec, initial: np.ndarray) -> Tuple[Optional[np.ndarray], float]:
    """Recover the board pose in the camera frame from detected corners.

    Levenberg-Marquardt on the six-parameter pose, seeded from ``initial``.
    A planar target admits a well-known two-fold pose ambiguity when viewed
    near fronto-parallel; seeding from a nearby pose picks the correct branch,
    which is what an initialiser from a homography decomposition would do in
    OpenCV. The ambiguity is real and it is why the generated poses are tilted.
    """
    visible = np.flatnonzero(np.all(np.isfinite(pixels), axis=1))
    if len(visible) < 6:
        return None, float("nan")

    corners = board_corners()[visible]
    observed = pixels[visible]

    def residual(parameters: np.ndarray) -> np.ndarray:
        pose = transform(Rotation.from_rotvec(parameters[:3]).as_matrix(), parameters[3:])
        points = corners @ pose[:3, :3].T + pose[:3, 3]
        depth = np.maximum(points[:, 2], 1e-6)
        u = camera.fx * points[:, 0] / depth + camera.cx
        v = camera.fy * points[:, 1] / depth + camera.cy
        return np.concatenate([u - observed[:, 0], v - observed[:, 1]])

    seed = np.concatenate([Rotation.from_matrix(initial[:3, :3]).as_rotvec(), initial[:3, 3]])
    solution = least_squares(residual, seed, method="lm", xtol=1e-12, ftol=1e-12)
    rms = float(np.sqrt(np.mean(solution.fun**2)))
    return transform(Rotation.from_rotvec(solution.x[:3]).as_matrix(), solution.x[3:]), rms


def generate_poses(
    board_pose: np.ndarray,
    count: int,
    rng: np.random.Generator,
    standoff: Tuple[float, float] = (0.30, 0.45),
    tilt: float = 0.42,
) -> List[np.ndarray]:
    """Camera poses that view the board from spread positions and orientations.

    Each pose looks at a point jittered off the board centre, from a position on
    a spherical cap above it, with a random roll about the view axis. The roll
    is what makes the rotation axes of the resulting *motions* non-parallel,
    and without it the translation of ``X`` is unobservable no matter how many
    poses are collected.
    """
    centre = np.asarray(board_pose)[:3, 3]
    poses = []
    for _ in range(count):
        azimuth = rng.uniform(-np.pi, np.pi)
        polar = rng.uniform(0.0, tilt)
        distance = rng.uniform(*standoff)
        direction = np.array(
            [np.sin(polar) * np.cos(azimuth), np.sin(polar) * np.sin(azimuth), np.cos(polar)]
        )
        eye = centre + direction * distance
        target = centre + np.concatenate([rng.normal(0.0, 0.012, 2), [0.0]])
        pose = look_at(eye, target, up=(1.0, 0.0, 0.0))
        roll = rng.uniform(-np.pi, np.pi)
        pose[:3, :3] = pose[:3, :3] @ Rotation.from_euler("z", roll).as_matrix()
        poses.append(pose)
    return poses


def collect_samples(
    arm,
    board_pose: np.ndarray,
    camera_poses: Sequence[np.ndarray],
    rng: np.random.Generator,
    encoder_noise_rad: float = 0.0,
) -> List[CalibrationSample]:
    """Drive the arm to each viewing pose and take a board measurement.

    Poses the arm cannot reach, or reaches only through a collision, are
    skipped -- which is what happens when a calibration routine is written
    without checking, and is why the number of usable poses is reported next to
    the residual.

    ``encoder_noise_rad`` perturbs the joint angles used to compute the flange
    pose. Set it non-zero to see what joint-encoder error or an imperfect
    robot kinematic model does to the result: hand-eye calibration assumes the
    robot's own forward kinematics is exact, and every error in it is absorbed
    into ``X`` as if it were a camera mounting error.
    """
    from cell_common.transforms import invert as _invert

    samples: List[CalibrationSample] = []
    truth = arm.cell.camera.extrinsic
    for camera_pose in camera_poses:
        tool = camera_pose @ _invert(truth) @ arm.tool_transform
        solution = arm.ik_nearest(tool, arm.cell.home_joints)
        if solution is None or not arm.is_valid(solution.joints, arm.gripper.max_opening, margin=0.01):
            continue

        joints = solution.joints
        if encoder_noise_rad > 0.0:
            joints = joints + rng.normal(0.0, encoder_noise_rad, size=6)

        actual_camera = arm.camera_pose(solution.joints)
        board_in_camera = _invert(actual_camera) @ board_pose
        pixels = project_corners(board_in_camera, arm.cell.camera)
        visible = int(np.sum(np.all(np.isfinite(pixels), axis=1)))
        if visible < 20:
            continue
        pixels = pixels + rng.normal(0.0, CORNER_NOISE_PIXELS, size=pixels.shape)

        # Seed PnP from a deliberately wrong pose so the solve is doing work.
        seed = board_in_camera.copy()
        seed[:3, 3] = seed[:3, 3] + rng.normal(0.0, 0.01, 3)
        seed[:3, :3] = seed[:3, :3] @ Rotation.from_rotvec(rng.normal(0.0, 0.02, 3)).as_matrix()

        recovered, rms = solve_pnp(pixels, arm.cell.camera, seed)
        if recovered is None:
            continue
        samples.append(
            CalibrationSample(
                flange_pose=arm.flange_pose(joints),
                board_in_camera=recovered,
                reprojection_rms=rms,
                visible_corners=visible,
            )
        )
    return samples


def tsai_lenz(motions: Sequence[Tuple[np.ndarray, np.ndarray]]) -> np.ndarray:
    """Solve ``A X = X B`` for X by the Tsai-Lenz closed form.

    Rotation first, from the modified Rodrigues vectors of each motion pair,
    then translation by linear least squares given that rotation. This is the
    method every industrial hand-eye routine has shipped since 1989; it is not
    the most accurate available -- a simultaneous nonlinear solve over all pairs
    does better with noisy data -- but it has no initialisation and no local
    minima, which is worth more on a shop floor than the last few hundredths of
    a degree.
    """
    rotation_rows = []
    rotation_targets = []
    for a, b in motions:
        pa = _modified_rodrigues(a[:3, :3])
        pb = _modified_rodrigues(b[:3, :3])
        rotation_rows.append(_skew(pa + pb))
        rotation_targets.append(pb - pa)
    stacked = np.vstack(rotation_rows)
    target = np.concatenate(rotation_targets)
    scaled, *_ = np.linalg.lstsq(stacked, target, rcond=None)

    norm_squared = float(scaled @ scaled)
    p = 2.0 * scaled / np.sqrt(1.0 + norm_squared)
    p_norm_squared = float(p @ p)
    rotation = (1.0 - p_norm_squared / 2.0) * np.eye(3) + 0.5 * (
        np.outer(p, p) + np.sqrt(max(4.0 - p_norm_squared, 0.0)) * _skew(p)
    )

    translation_rows = []
    translation_targets = []
    for a, b in motions:
        translation_rows.append(a[:3, :3] - np.eye(3))
        translation_targets.append(rotation @ b[:3, 3] - a[:3, 3])
    translation, *_ = np.linalg.lstsq(np.vstack(translation_rows), np.concatenate(translation_targets), rcond=None)
    return transform(rotation, translation)


def _modified_rodrigues(rotation: np.ndarray) -> np.ndarray:
    """2 sin(theta/2) times the rotation axis, the Tsai-Lenz parameterisation."""
    rotvec = Rotation.from_matrix(rotation).as_rotvec()
    angle = float(np.linalg.norm(rotvec))
    if angle < 1e-12:
        return np.zeros(3)
    return 2.0 * np.sin(angle / 2.0) * (rotvec / angle)


def calibrate(samples: Sequence[CalibrationSample], min_rotation: float = np.radians(8.0)) -> CalibrationResult:
    """Solve for the flange-to-camera transform from a set of samples.

    Motion pairs whose rotation is smaller than ``min_rotation`` are dropped.
    Tsai-Lenz divides by the sine of half the motion angle in effect, so a
    nearly-pure translation contributes almost nothing but its noise, and
    including them makes the answer worse the more data you collect -- which is
    a genuinely confusing failure to debug on hardware.
    """
    motions: List[Tuple[np.ndarray, np.ndarray]] = []
    axes: List[np.ndarray] = []
    for i in range(len(samples)):
        for j in range(i + 1, len(samples)):
            a = invert(samples[j].flange_pose) @ samples[i].flange_pose
            b = samples[j].board_in_camera @ invert(samples[i].board_in_camera)
            rotvec = Rotation.from_matrix(a[:3, :3]).as_rotvec()
            angle = float(np.linalg.norm(rotvec))
            if angle < min_rotation:
                continue
            motions.append((a, b))
            axes.append(rotvec / angle)
    if len(motions) < 3:
        raise ValueError("not enough rotating motion pairs to solve AX = XB")

    solution = tsai_lenz(motions)

    rotation_errors = []
    translation_errors = []
    for a, b in motions:
        residual = invert(a @ solution) @ (solution @ b)
        rotation_errors.append(np.degrees(np.linalg.norm(Rotation.from_matrix(residual[:3, :3]).as_rotvec())))
        translation_errors.append(np.linalg.norm(residual[:3, 3]) * 1000.0)

    # Where each sample thinks the board is, in the world. The spread of that
    # cloud is the most legible field diagnostic there is: a good calibration
    # puts them all in the same place.
    board_estimates = np.array(
        [(sample.flange_pose @ solution @ sample.board_in_camera)[:3, 3] for sample in samples]
    )
    spread = float(np.max(np.linalg.norm(board_estimates - board_estimates.mean(axis=0), axis=1)) * 1000.0)

    axis_array = np.array(axes)
    dots = np.abs(axis_array @ axis_array.T)
    spread_deg = float(np.degrees(np.arccos(np.clip(np.min(dots), -1.0, 1.0))))

    return CalibrationResult(
        transform=solution,
        sample_count=len(samples),
        pair_count=len(motions),
        consistency_rotation_deg=float(np.mean(rotation_errors)),
        consistency_translation_mm=float(np.mean(translation_errors)),
        board_spread_mm=spread,
        reprojection_rms=float(np.mean([sample.reprojection_rms for sample in samples])),
        rotation_axis_spread_deg=spread_deg,
    )
